# Token‑checked lock renewal – succeeds only if token matches, sets new TTL.
RENEW_LOCK_LUA = """
if redis.call('get', KEYS[1]) == ARGV[1] then
    return redis.call('expire', KEYS[1], ARGV[2])
else
    return 0
end
"""

# Token‑checked lock release – succeeds and deletes only if token matches.
RELEASE_LOCK_LUA = """
if redis.call('get', KEYS[1]) == ARGV[1] then
    return redis.call('del', KEYS[1])
else
    return 0
end
"""

# ----------------------------------------------------------------------
# ASSIGN_REPORT_ATOMIC_LUA
# --------------------------------------------------------------
# KEYS:
#   1 = permanent mapping key          (report_incident:<report_id>)
#   2 = processing lock key           (lock:report:<report_id>)
#   3 = incident hash key             (incident:<incident_id>)
#   4 = incident reports set key      (incident:reports:<incident_id>)
# ARGV:
#   1 = report_id
#   2 = incident_id (generated by caller when create_flag==1)
#   3 = timestamp ISO string (now)
#   4 = create_flag (1 = create new incident, 0 = attach only)
#   5 = processing lock token (exact token to validate ownership)
#   6 = creation lock token (optional, only used when create_flag==1)
#   7 = equipment_id (may be empty string)
#   8 = category (may be empty string)
#   9 = location (may be empty string)
#   10 = status for new incident (defaults to OPEN)
#   11 = created_at timestamp (same as now)
# --------------------------------------------------------------
ASSIGN_REPORT_ATOMIC_LUA = """
-- Validate processing lock ownership
local lock_key = KEYS[2]
local lock_val = redis.call('GET', lock_key)
if lock_val ~= ARGV[5] then
    return redis.error_reply('Processing lock token mismatch')
end

local perm_key = KEYS[1]
local existing = redis.call('GET', perm_key)
if existing then
    -- Mapping already exists – return it, no changes
    return {existing, 0}
end

local incident_id = ARGV[2]
local create_flag = tonumber(ARGV[4])
local now_ts = ARGV[3]
local inc_hash = KEYS[3]
local inc_set = KEYS[4]
local report_id = ARGV[1]

if create_flag == 1 then
    -- New incident: initialize hash with all required fields
    redis.call('HSET', inc_hash,
        'incident_id', incident_id,
        'equipment_id', ARGV[7],
        'category', ARGV[8],
        'location', ARGV[9],
        'status', ARGV[10],
        'created_at', ARGV[11],
        'updated_at', now_ts,
        'report_count', 1,
        'latest_report_id', report_id)
    -- Add the report to the set (first member)
    redis.call('SADD', inc_set, report_id)
    -- Write permanent mapping
    redis.call('SET', perm_key, incident_id)
    return {incident_id, 1}
else
    -- Attach to existing incident – verify hash exists
    if redis.call('EXISTS', inc_hash) == 0 then
        return redis.error_reply('Target incident hash does not exist')
    end
    local added = redis.call('SADD', inc_set, report_id)
    local new_count = 0
    if added == 1 then
        new_count = redis.call('HINCRBY', inc_hash, 'report_count', 1)
        redis.call('HSET', inc_hash, 'updated_at', now_ts, 'latest_report_id', report_id)
    else
        new_count = tonumber(redis.call('HGET', inc_hash, 'report_count')) or 0
    end
    -- Write permanent mapping
    redis.call('SET', perm_key, incident_id)
    return {incident_id, new_count}
end
"""
